-- V1: Baseline schema.
--
-- This mirrors exactly what Hibernate's `ddl-auto: update` generated before
-- Flyway was introduced (captured with pg_dump from the original code).
--
-- * An EXISTING database that already has these tables is not touched by this
--   file: `spring.flyway.baseline-on-migrate` marks version 1 as already applied.
-- * A NEW, empty database (tests, CI, production) runs this file normally.
--
-- Never edit this file after it has been applied anywhere. Flyway stores a
-- checksum of every applied migration and refuses to start if it changes.
-- Schema changes always go into a new V<n>__description.sql file.

CREATE TABLE users (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accessed_at TIMESTAMP(6) WITH TIME ZONE,
    created_at  TIMESTAMP(6) WITH TIME ZONE,
    email       VARCHAR(255),
    password    VARCHAR(255),
    role        VARCHAR(255),
    user_name   VARCHAR(255)
);

CREATE TABLE posts (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    body       VARCHAR(255),
    created_at TIMESTAMP(6) WITH TIME ZONE,
    user_id    INTEGER NOT NULL,
    CONSTRAINT fk_posts_user FOREIGN KEY (user_id) REFERENCES users (id)
);
